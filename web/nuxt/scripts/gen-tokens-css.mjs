#!/usr/bin/env node
/**
 * gen-tokens-css.mjs — emits `app/assets/css/10-tokens.css` from `shared/tokens.ts`.
 *
 *   node scripts/gen-tokens-css.mjs           # write
 *   node scripts/gen-tokens-css.mjs --check   # exit 1 if the file on disk is stale
 *
 * Run `--check` in CI / a pre-commit hook. A stale tokens file is the single most
 * likely way this design system silently drifts: `#00E0FF` used to be hand-written
 * in five places (styles.css, charts.js, INDEX.md, the Android theme, the LVGL
 * theme). This script makes the CSS a build artefact of exactly one of them.
 *
 * Requires Node >= 22.6 (native TypeScript type-stripping) to import the .ts
 * source directly. Node >= 23.6 needs no flag; 22.6–23.5 needs
 * `--experimental-strip-types`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  BORDER,
  CHART,
  CHART_GLOW_SCALE,
  CSS_ALIAS,
  FONT,
  GLOW_SOFT_SCALE,
  GLOW_TOKENS,
  GLYPH_GLOW,
  GRID,
  GRID_ALPHA,
  HIGH_CONTRAST,
  NEON,
  RADIUS,
  SUBSTRATE,
  TEXT,
  TRANSITION,
  glowString,
  hexA,
} from '../shared/tokens.ts'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'app', 'assets', 'css', '10-tokens.css')

const lc = (s) => s.toLowerCase()
const L = []
const push = (...s) => L.push(...(s.length ? s : ['']))

push('/* ============================================================================')
push(' * 10-tokens.css — GENERATED by scripts/gen-tokens-css.mjs from shared/tokens.ts')
push(' * DO NOT HAND-EDIT. Run `npm run tokens` after changing shared/tokens.ts.')
push(' * `npm run tokens:check` fails if this file is stale.')
push(' *')
push(' * Hex values are byte-identical to INDEX.md and web/petite-vue/styles.css.')
push(' * ==========================================================================*/')
push('')
push('@layer neon.tokens {')
push('')
push('  /* ---- BASE SET = GLOW "full". A missing [data-glow] attribute therefore')
push('     degrades to the shipped look, never to an unstyled page. `soft` and `off`')
push('     override below; the layer ships <html data-glow="soft"> as the default. -- */')
push('  :root {')

push('    /* substrate */')
push(`    --bg-darkest: ${lc(SUBSTRATE.darkest)};`)
push(`    --bg-dark: ${lc(SUBSTRATE.dark)};`)
push(`    --bg-panel: ${lc(SUBSTRATE.panel)};`)
push(`    --bg-panel-hover: ${lc(SUBSTRATE.panelHover)};`)
push(`    --bg-input: ${lc(SUBSTRATE.input)};`)
push(`    --bg-elevated: ${lc(SUBSTRATE.elevated)};`)
push('')
push('    /* borders */')
push(`    --border-base: ${lc(BORDER.base)};`)
push(`    --border-glow: ${lc(BORDER.glow)};`)
push(`    --border-glow-dim: ${BORDER.glowDim};`)
push(`    --cyan-dim: ${BORDER.cyanDim};`)
push('')
push('    /* spectrum */')
for (const [k, v] of Object.entries(NEON)) {
  const name = CSS_ALIAS[k] ?? k
  push(`    --${name}: ${lc(v)};`)
}
push(`    /* alias so both vocabularies work: INDEX.md says "Fuchsia", CSS says --magenta */`)
push(`    --fuchsia: var(--magenta);`)
push('')
push('    /* text */')
push(`    --text-primary: ${lc(TEXT.primary)};`)
push(`    --text-secondary: ${lc(TEXT.secondary)};`)
push(`    --text-dim: ${lc(TEXT.dim)};        /* decorative only: dividers, disabled, placeholder */`)
push(`    --text-label: ${lc(TEXT.label)};      /* every VISIBLE label/caption — AA at label sizes */`)
push(`    --violet-text: ${lc(TEXT.violet)};     /* ANY violet glyph (--violet is strokes/borders only) */`)
push(`    --red-text: ${lc(TEXT.red)};`)
push(`    --green-text: ${lc(TEXT.green)};`)
push('')
push('    /* type */')
push(`    --font-display: ${FONT.display};`)
push(`    --font-mono: ${FONT.mono};`)
push('    /* per-user transcript sizing — a text-size control, not browser zoom,')
push('       so the chrome stays put while dense mono content scales */')
push('    --transcript-size: 1.04rem;')
push('')
push('    /* container border weight — thickened to 2px under high contrast */')
push('    --border-width: 1px;')
push('')
push('    /* corners — 6/8/12/20 */')
push(`    --radius-xs: ${RADIUS.xs}px;`)
push(`    --radius-sm: ${RADIUS.sm}px;`)
push(`    --radius: ${RADIUS.md}px;`)
push(`    --radius-lg: ${RADIUS.lg}px;`)
push('')
push(`    --transition: ${TRANSITION};`)
push('')
push('    /* grid substrate (no scanlines — intentionally omitted on every platform) */')
push(`    --grid-size: ${GRID.size}px;`)
push(`    --grid-drift: ${GRID.drift}px;`)
push(`    --grid-alpha: ${GRID_ALPHA.full};`)
push(`    --grid-color: rgba(0,224,255,var(--grid-alpha));`)
push('')
push('    /* glow — box-shadow ramps */')
for (const [name, { color, spec }] of Object.entries(GLOW_TOKENS)) {
  push(`    --glow-${name}: ${glowString(color, spec)};`)
}
push('')
push('    /* glow — glyph text-shadow (gated separately: it is the harmful one) */')
push(`    --glyph-glow: ${GLYPH_GLOW.full};`)
push('    /* glow — canvas bloom multiplier, read by useNeonChart() */')
push(`    --chart-glow-scale: ${CHART_GLOW_SCALE.full};`)
push('    /* glow — SVG filter bloom radii, read by <NgSvgDefs> */')
push('    --svg-glow-outer: 6.5;')
push('    --svg-glow-inner: 2.4;')
push('')
push('    /* chart parity */')
for (const [k, v] of Object.entries(NEON)) {
  const name = CSS_ALIAS[k] ?? k
  push(`    --chart-${name}-fill: ${hexA(v, CHART.fillAlpha)};`)
}
push(`    --chart-grid-line: ${CHART.gridLine};`)
push(`    --chart-axis-line: ${CHART.axisLine};`)
push(`    --chart-tick-text: var(--text-label);`)
push(`    --chart-tooltip-bg: ${CHART.tooltipBg};`)
push('  }')
push('')

/* ---- soft ------------------------------------------------------------- */
push(`  /* ---- GLOW "soft" — DEFAULT. radii x${GLOW_SOFT_SCALE.radius}, alphas x${GLOW_SOFT_SCALE.alpha}, third stop dropped.`)
push('     The box-shadow bloom on panels and pills is what carries the look; the')
push('     glyph text-shadow is what blurs glyph edges for the ~50% of people with')
push('     astigmatism. soft keeps the first and halves the second. ---------------- */')
push('  :root[data-glow="soft"] {')
for (const [name, { color, spec }] of Object.entries(GLOW_TOKENS)) {
  push(
    `    --glow-${name}: ${glowString(color, spec, {
      radiusScale: GLOW_SOFT_SCALE.radius,
      alphaScale: GLOW_SOFT_SCALE.alpha,
      stops: GLOW_SOFT_SCALE.stops,
    })};`,
  )
}
push(`    --glyph-glow: ${GLYPH_GLOW.soft};`)
push(`    --grid-alpha: ${GRID_ALPHA.soft};`)
push(`    --chart-glow-scale: ${CHART_GLOW_SCALE.soft};`)
push('    --svg-glow-outer: 4;')
push('    --svg-glow-inner: 1.6;')
push('  }')
push('')

/* ---- off -------------------------------------------------------------- */
push('  /* ---- GLOW "off" — no bloom anywhere. Colour, borders and gradient')
push('     hairlines still carry the identity. This is the long-shift setting. ----- */')
push('  :root[data-glow="off"] {')
for (const name of Object.keys(GLOW_TOKENS)) {
  push(`    --glow-${name}: none;`)
}
push(`    --glyph-glow: ${GLYPH_GLOW.off};`)
push(`    --grid-alpha: ${GRID_ALPHA.off};`)
push(`    --chart-glow-scale: ${CHART_GLOW_SCALE.off};`)
push('    --svg-glow-outer: 0.001;')
push('    --svg-glow-inner: 0.001;')
push('  }')
push('')

/* ---- high contrast ---------------------------------------------------- */
push('  /* ---- HIGH CONTRAST. Driven by BOTH an explicit attribute and the OS')
push('     preference. Forces glow off as well — a glow is spent contrast. ------- */')
const hcBody = []
for (const [k, v] of Object.entries(HIGH_CONTRAST)) hcBody.push(`    ${k}: ${v};`)
for (const name of Object.keys(GLOW_TOKENS)) hcBody.push(`    --glow-${name}: none;`)
hcBody.push(`    --glyph-glow: ${GLYPH_GLOW.off};`)
hcBody.push(`    --grid-alpha: ${GRID_ALPHA.off};`)
hcBody.push(`    --chart-glow-scale: 0;`)
hcBody.push('    --svg-glow-outer: 0.001;')
hcBody.push('    --svg-glow-inner: 0.001;')
hcBody.push('    --border-width: 2px;')

push('  :root[data-contrast="high"] {')
push(...hcBody)
push('  }')
push('')
push('  @media (prefers-contrast: more) {')
push('    :root:not([data-contrast="normal"]) {')
push(...hcBody.map((l) => '  ' + l))
push('    }')
push('  }')
push('}')
push('')

const out = L.join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing counts as stale */
  }
  if (current.replace(/\r\n/g, '\n') !== out) {
    console.error('[neon-grid] 10-tokens.css is STALE. Run `npm run tokens`.')
    process.exit(1)
  }
  console.log('[neon-grid] 10-tokens.css is up to date.')
} else {
  writeFileSync(OUT, out, 'utf8')
  console.log(`[neon-grid] wrote ${OUT} (${out.length} bytes)`)
}
